// The includer provides `snap` (the snapshot module: `use content_hub_core::snapshot as snap;` or `use crate::snapshot as snap;`).
// Shared by `examples/gen-snapshot-fixture.rs` (which writes the file) and the test that proves the committed file is
// what the code produces. `include!`d, not a module, so neither needs a public API for it.
//
// The seed is a TEST key (32 bytes of 0x07): it signs nothing real and holds nothing. The fixture is checked in CI
// against `@mysten/sui`'s `verifyPersonalMessageSignature` (tests/contract/snapshot.test.ts).
fn snapshot_fixture() -> serde_json::Value {
    use base64::Engine;
    use serde_json::json;
    let seed = [7u8; 32];
    let signer = snap::Signer::from_seed(&seed).expect("test seed");
    let long = format!("Opens soon — café ☕ {}", "x".repeat(200));
    let doc = json!({
        "schema": snap::SCHEMA,
        "human": {
            "schema_version": 1,
            "updated_at": "2026-10-29T12:00:00Z",
            "phases": [{
                "id": "6b9c5c8e-0000-4000-8000-000000000001",
                "name": "Launch",
                "description": "The first public phase",
                "window_start": null,
                "window_end": null,
                "items": [{
                    "id": "6b9c5c8e-0000-4000-8000-000000000002",
                    "title": "Mint",
                    "description": long,
                    "status": "planned",
                    "due_at": "2027-03-01T12:00:00Z",
                    "updated_at": "2026-10-29T12:00:00Z"
                }]
            }]
        },
        "bot": { "schema_version": 1, "updated_at": null, "phases": [] }
    });
    let message = snap::canonical(&doc).expect("canonical");
    let signature = signer.sign_personal_message(&message);
    json!({
        "description": "A snapshot signed by a TEST key (seed = 32 bytes of 0x07). Generated by `cargo run -p content-hub-core --example gen-snapshot-fixture`; verified with @mysten/sui in CI.",
        "address": signer.address(),
        "sha256": snap::sha256_hex(&message),
        "message_utf8_length": message.len(),
        "message_base64": base64::engine::general_purpose::STANDARD.encode(&message),
        "signature": signature,
    })
}
